const cards = new Map(
  cardRows.map(([name, oracleId, manaCost, manaValue, typeLine, colorIdentity, image]) => [
    name,
    {
      oracleId,
      name,
      frontFaceName: name,
      manaCost,
      manaValue,
      typeLine,
      colorIdentity,
      imageSmall: `https://cards.scryfall.io/small/${image}`,
      imageNormal: `https://cards.scryfall.io/normal/${image}`,
      canBeCommander: commanderNames.has(name),
      isBasicLand: basicLandNames.has(name),
    } satisfies CardSummary,
  ]),
);

/** A card of the Hearthhull deck (or one the update sample swaps in), by name. */
export function sampleCard(name: string): CardSummary {
  const card = cards.get(name);
  if (!card) throw new Error(`No sample card named ${name}`);
  return card;
}

/** A slot of a card in the sample data, with the printing hint its line named. */
export function sampleSlot(
  name: string,
  board: Board,
  quantity: number,
  setCode: string,
  collectorNumber: string,
  foil = false,
): ParsedSlot {
  return { card: sampleCard(name), board, quantity, hint: { setCode, collectorNumber, foil } };
}

